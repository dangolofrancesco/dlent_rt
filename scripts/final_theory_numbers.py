"""
Week 33: the raw numbers of reports/week33/final_theory.md, from the model-check caches (scan, week, theory) and one
Phase 0 at the configured f. Kept to reproduce that report: its f_scan.pkl (rule with fluid OPT on the stream) and
week_milp.pkl (bucketed MILP) come from the code of commit 7f2f7fa; the current rule is on H (scripts/select_f.py)
and the current discretization cost is scripts/discretization_milp.py.

    dlent_venv/bin/python scripts/model_check_cache.py scan     # then week and theory
    dlent_venv/bin/python scripts/final_theory_numbers.py       # -> reports/week33/final_theory_numbers.md
"""
from __future__ import annotations

import pickle, sys, warnings
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT), str(ROOT / "scripts")]
CACHE = ROOT / "reports" / "week33" / "cache"
OUT = ROOT / "reports" / "week33" / "final_theory_numbers.md"


def md(df: pd.DataFrame, floatfmt="{:,.4g}") -> str:
    df = df.copy()
    for c in df.columns:
        df[c] = [floatfmt.format(x) if isinstance(x, (float, np.floating)) else x for x in df[c]]
    head = "| " + " | ".join(str(c) for c in [df.index.name or ""] + list(df.columns)) + " |"
    sep = "|" + "---|" * (len(df.columns) + 1)
    rows = ["| " + " | ".join([str(i)] + [str(v) for v in r]) + " |" for i, r in zip(df.index, df.values)]
    return "\n".join([head, sep, *rows])


def main() -> None:
    warnings.simplefilter("ignore")
    from dlent_rt.config import default_config
    from dlent_rt.data import load_dataset
    from dlent_rt.phase0 import run_phase0
    from truthful_batch import phase0_numbers
    cfg = default_config()
    f = cfg.capacity.f
    scan = pickle.load(open(CACHE / "f_scan.pkl", "rb"))
    week = pickle.load(open(CACHE / "week_milp.pkl", "rb"))
    run = pickle.load(open(CACHE / "theory_run.pkl", "rb"))
    assert run["f"] == f and week["f"] == f, "caches at another f"
    R0 = next(r for r in scan["results"] if r["f"] == f)
    ds = load_dataset(cfg)
    st = run_phase0(ds, cfg)
    p0 = phase0_numbers(ds, st, cfg)
    out = [f"# Week 33: final theory, raw numbers (f = {f}, seed {cfg.run.seed})", "",
           "Generated by `scripts/final_theory_numbers.py` from `reports/week33/cache/`.", ""]

    # 1. f scan
    rows = []
    for r in scan["results"]:
        rows.append({"f": r["f"], "C CPU": r["C"][0], "C RAM": r["C"][1], "stream jobs": r["n_stream"],
                     "tau Phase 0 (CPU, RAM)": str(np.round(r["phase0_lp"]["tau"], 6).tolist()),
                     "tau fluid (CPU, RAM)": str(np.round(r["fluid"]["tau"], 6).tolist()),
                     "(a) tau > 0 in both": bool(np.any(np.asarray(r["phase0_lp"]["tau"]) > 0)
                                                 and np.any(np.asarray(r["fluid"]["tau"]) > 0)),
                     "static: % time >= 95% full": 100 * r["static"]["full_time"],
                     "fluid OPT $": r["fluid"]["split"]["reward"], "static $": r["static"]["split"]["reward"],
                     "no-learning $": r["no_learning"]["split"]["reward"]})
    out += ["## 1. f scan", "", md(pd.DataFrame(rows).set_index("f")), "",
            f"Rule picks f = {scan['selected']}; configs/default.yaml has f = {scan['config_f']}.", ""]

    # 2. Phase 0 at f
    g = p0["grid"]
    p0rows = {"U0 ($/h)": p0["U0 ($/h)"], "sigma": p0["sigma"], "v_min ($/h)": g["v_min ($/h)"],
              "v_max ($/h)": g["v_max ($/h)"], "rho": g["rho"], "1 - 1/rho": 1 - 1 / g["rho"],
              "bins used by H": g["bins used by H"], "s_C ($/kg)": p0["s_C ($/kg)"],
              "D_q ($)": p0["norm_info"]["D_q"], "K_q (kg)": p0["norm_info"]["K_q"],
              "tau CPU": p0["tau (CPU, RAM)"][0], "tau RAM": p0["tau (CPU, RAM)"][1],
              "LP fill CPU": p0["LP fill (CPU, RAM)"][0], "LP fill RAM": p0["LP fill (CPU, RAM)"][1],
              "LP optimum ($/h)": p0["LP optimum ($/h)"], "populated types": p0["populated types"],
              "% populated types with r~ > 0": p0["% populated types with r~ > 0"],
              "% of H's arrival rate with r~ > 0": p0["% of H's arrival rate on types with r~ > 0"],
              "% of H jobs at or above k*": p0["% of H jobs in a bin >= k* of their column (Phase 0 state)"],
              "columns with k* = 0": p0["columns with k* = 0"], "columns with no H job": p0["columns with no H job (fallback)"],
              "r_max, Tests 2-3 unit ($)": p0["r_max (Tests 2-3 unit)"]}
    sh = pd.DataFrame({"over LP-admitted mass": p0["term shares, over the LP's admitted mass p x"],
                       "over types with r~ > 0": p0["term shares, p-weighted over H's types with r~ > 0"]}).T * 100
    out += ["## 2. Phase 0 at the chosen f", "", md(pd.Series(p0rows, name="value").to_frame()), "",
            "Objective shares (% of sum |term|):", "", md(sh, "{:.1f}"), ""]

    # 3. one-week MILP
    best, bound = week["bucketed_believed"], min(week["bucketed_dual_bound"], week["bucketed_lp_believed"])
    ff = week["fluid_feasible"]
    wk = {"jobs": week["n_jobs"], "MILP candidates": week["n_candidates"], "nonzeros": week["nonzeros"],
          "fluid, volume inside the window $": week["fluid"], "fluid on feasible types, inside $": ff,
          "fluid, whole volume $": week["fluid_whole_volume"], "MILP best $": best, "MILP bound $": bound,
          "MILP gap %": 100 * week["gap"], "MILP status": week["status"], "MILP runtime s": week["milp_runtime_s"],
          "feasible on true durations": week["feasible_true"],
          "discretization cost $ (best)": ff - best, "discretization cost $ (bound)": ff - bound,
          "discretization cost % (best)": 100 * (ff - best) / ff, "discretization cost % (bound)": 100 * (ff - bound) / ff,
          "grid worst case 1 - 1/rho %": 100 * (1 - 1 / g["rho"]), "MILP realised (job rewards) $": week["bucketed_realised"]}
    out += ["## 3. One-week bucketed MILP (days 0-7 of the stream)", "", md(pd.Series(wk, name="value").to_frame()), ""]

    # 4. full run
    ph, sm, ck = run["phases"], run["summary"], run["checks"]
    h = cfg.time.tick_seconds / 3600
    tick, R = np.asarray(run["tick"]), np.asarray(run["R_job"])
    nl_adm, st_adm = np.asarray(R0["no_learning"]["admit"]), np.asarray(R0["static"]["admit"])
    per = []
    for _, p in ph.iterrows():
        w = (tick >= p.tau_start) & (tick <= p.tau_end)
        per.append({"phase": int(p.m), "start h": (p.tau_start - 1) * h, "length h": p.W * h, "end": p.reason,
                    "arrivals": int(p.n_arrivals), "admitted": int(p.n_admitted), "tau CPU": p.tau_cpu,
                    "tau RAM": p.tau_ram, "sigma": p.sigma, "DLENT-RT $": p.R,
                    "no-learning $": float(R[w & nl_adm].sum()), "static $": float(R[w & st_adm].sum()),
                    "fluid on the phase (hindsight) $": p.bench_hindsight})
    per = pd.DataFrame(per).set_index("phase")
    tot = per[["length h", "arrivals", "admitted", "DLENT-RT $", "no-learning $", "static $",
               "fluid on the phase (hindsight) $"]].sum()
    out += [f"## 4. Full theoretical run (runtime {run['runtime_s'] / 60:,.0f} min)", "", "Phases:", "",
            md(per), "", "Sum over phases: " + ", ".join(f"{k} {v:,.2f}" for k, v in tot.items()), ""]
    A = run["arrivals"]
    adm = A[A.admit]
    comp = pd.DataFrame({
        "fluid OPT": dict(R0["fluid"]["split"], admitted=np.nan, payments=np.nan),
        "DLENT-RT": {"customer value": float(adm.value.sum()), "profit": ck["myerson"]["expected_profit"],
                     "carbon": float(sm["R_total"] - adm.value.sum() - ck["myerson"]["expected_profit"]),
                     "reward": sm["R_total"], "social welfare": sm["SW_total"], "admitted": sm["n_admitted"],
                     "payments": sm["payments_total"]},
        "no-learning": dict(R0["no_learning"]["split"], admitted=R0["no_learning"]["n_admitted"],
                            payments=R0["no_learning"]["mechanism"]["payments"]),
        "static": dict(R0["static"]["split"], admitted=R0["static"]["n_admitted"],
                       payments=R0["static"]["mechanism"]["payments"])}).T
    comp["% of fluid OPT"] = 100 * comp["reward"] / R0["fluid"]["split"]["reward"]
    out += ["Comparison ($ over the stream):", "", md(comp, "{:,.2f}"), ""]
    mech = pd.DataFrame({
        "DLENT-RT": {"payments $": sm["payments_total"], "payments - C_elec $": ck["myerson"]["realised_profit"],
                     "expected profit sum(phi d - C_elec) $": ck["myerson"]["expected_profit"],
                     "mean p / b": ck["run"]["payments"]["mean p / b"],
                     "set by the reserve": ck["run"]["payments"]["share set by the reserve (r > L_k*)"],
                     "IR violations": ck["run"]["IR violations"],
                     "upper-set violations": ck["run"]["upper-set violations (phase states)"]
                     + ck["run"]["upper-set violations (run: a bin rejected above an admitted bin, same phase and column)"],
                     **{f"rejected: {k}": v for k, v in ck["run"]["rejections"].items()}},
        **{name: {"payments $": R0[k]["mechanism"]["payments"], "payments - C_elec $": R0[k]["profit_payments"],
                  "expected profit sum(phi d - C_elec) $": R0[k]["split"]["profit"],
                  "mean p / b": R0[k]["mechanism"]["payment_rate_over_bid_mean"],
                  "set by the reserve": R0[k]["mechanism"]["share_payment_by_reserve"],
                  "IR violations": R0[k]["mechanism"]["n_ir_violations"],
                  "upper-set violations": R0[k]["mechanism"]["n_upper_set_violations"],
                  **{f"rejected: {r}": n for r, n in R0[k]["mechanism"]["rejections"].items()}}
           for name, k in (("no-learning", "no_learning"), ("static", "static"))}}).T
    out += ["Mechanism checks:", "", md(mech, "{:,.4g}"), ""]
    sc = ck["spot_check"]
    out += [f"Truthfulness spot check: {sc['admitted checked']} admitted + {sc['rejected checked']} rejected, "
            f"{sc['decisions re-run']} decisions re-run (bids x 0.5, 0.8, 1.25, 2), logged k* != recomputed: "
            f"{sc['logged k* != recomputed k*']}, violations: {sc['violations']}.", "",
            f"End reasons: {sm['phase_end_reasons']}. Phases: {sm['n_phases']}. Short phases: {sm['n_short_phases']}.",
            f"Median job bin - median k* per column (10/50/90 %): "
            f"{ck['run']['median job bin - median k*, over columns (arrival-weighted quantiles 10/50/90)']}.", ""]
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
